class Window:
    def __init__(self) -> None:
        self.running = False
        self.isRotating = 1
        self.rotSpeed = 1
    def leftClick(self,Mousepos):
        match self.isRotating:
            case 0:
                self.isRotating = 1
            case 1:
                self.isRotating = 0
    def rightClick(self,Mousepos):
        pass
    def mwheel(self,e):
        self.rotSpeed += e.y 
    def run(self):
        self.running = True
        while self.running:
            for event in pygame.event.get():
                if event.type == pygame.QUIT:
                    pygame.quit()
                    self.running = False
                    quit()
                elif event.type == pygame.MOUSEBUTTONDOWN:
                    match event.button:
                        case 1:
                            self.leftClick(pygame.mouse.get_pos())
                        case 3:
                            self.rightClick(pygame.mouse.get_pos())
                elif event.type == pygame.MOUSEWHEEL:
                    self.mwheel(event)
            # main loop
            clock.tick(FPS)
            pygame.draw.rect(screen, BackgroundColor, pygame.Rect(0, 0, width, height)) # empty
            
            self.update([klein])
            
            pygame.display.flip()
    def update(self, objs):
        for obj in objs:
            obj.draw()
            obj.angle += dt*pi*0.5*self.isRotating*self.rotSpeed
            
        
